
USE gym_management_db;

-- 1. Display all gym members
SELECT * FROM members;

-- 2. Find members who joined between January and March 2026
SELECT member_id, first_name, last_name, join_date
FROM members
WHERE join_date BETWEEN '2026-01-01' AND '2026-03-31';

-- 3. Find members whose first name starts with A
SELECT member_id, first_name, last_name
FROM members
WHERE first_name LIKE 'A%';

-- 4. Display all unique membership statuses
SELECT DISTINCT status
FROM memberships;

-- 5. Display members with their membership plan details
SELECT
    m.member_id,
    m.first_name,
    m.last_name,
    p.plan_name,
    p.price
FROM members m
INNER JOIN memberships ms
    ON m.member_id = ms.member_id
INNER JOIN plans p
    ON ms.plan_id = p.plan_id;

-- 6. Find members enrolled in Monthly or Quarterly plans
SELECT
    m.first_name,
    m.last_name,
    p.plan_name
FROM members m
INNER JOIN memberships ms
    ON m.member_id = ms.member_id
INNER JOIN plans p
    ON ms.plan_id = p.plan_id
WHERE p.plan_name IN ('Monthly', 'Quarterly');

-- 7. Display the five most expensive membership plans
SELECT plan_name, duration_months, price
FROM plans
ORDER BY price DESC
LIMIT 5;

-- 8. Display all members in alphabetical order
SELECT member_id, first_name, last_name
FROM members
ORDER BY first_name ASC;


-- 9. Count the number of memberships under each plan
SELECT
    p.plan_name,
    COUNT(ms.membership_id) AS total_memberships
FROM plans p
LEFT JOIN memberships ms
    ON p.plan_id = ms.plan_id
GROUP BY p.plan_id, p.plan_name
ORDER BY total_memberships DESC;


-- 10. Calculate total revenue generated by each trainer
SELECT
    t.trainer_name,
    SUM(pay.amount) AS total_revenue
FROM trainers t
INNER JOIN memberships ms
    ON t.trainer_id = ms.trainer_id
INNER JOIN payments pay
    ON ms.membership_id = pay.membership_id
WHERE pay.payment_status = 'PAID'
GROUP BY t.trainer_id, t.trainer_name
ORDER BY total_revenue DESC;


-- 11. Find the number of new members joining each month
SELECT
    DATE_FORMAT(join_date, '%Y-%m') AS joining_month,
    COUNT(member_id) AS new_members
FROM members
GROUP BY DATE_FORMAT(join_date, '%Y-%m')
ORDER BY joining_month;


-- 12. Find members who have not recorded attendance
SELECT
    m.member_id,
    m.first_name,
    m.last_name
FROM members m
LEFT JOIN attendance a
    ON m.member_id = a.member_id
WHERE a.attendance_id IS NULL;


-- 13. Find members whose total payments exceed Rs. 5000
SELECT
    m.member_id,
    m.first_name,
    m.last_name,
    SUM(pay.amount) AS total_paid
FROM members m
INNER JOIN memberships ms
    ON m.member_id = ms.member_id
INNER JOIN payments pay
    ON ms.membership_id = pay.membership_id
WHERE pay.payment_status = 'PAID'
GROUP BY m.member_id, m.first_name, m.last_name
HAVING SUM(pay.amount) > 5000
ORDER BY total_paid DESC;

